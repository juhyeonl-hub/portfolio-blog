import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {moduleUrl} from './modules.mjs';
const {parseDpsSnapshot:parse}=await import(moduleUrl(readFileSync('lib/live-dps.ts','utf8')));
const sample={v:1,target:'Synthetic target',mode:'bossTargets',timeMs:10000,rows:[{name:'Synthetic test',dps:123,dmg:1234,you:true}]};
assert.deepEqual(parse(sample),sample);
for(const patch of [{v:2},{timeMs:-1},{timeMs:NaN},{rows:null},{rows:[null]},{rows:Array(65).fill(sample.rows[0])}]) assert.throws(()=>parse({...sample,...patch}));
for(const patch of [{dps:-1},{dps:1.5},{dps:Infinity},{dmg:Number.MAX_SAFE_INTEGER+1},{you:1},{name:'x'.repeat(129)}]) assert.throws(()=>parse({...sample,rows:[{...sample.rows[0],...patch}]}));
assert.equal(parse({...sample,rows:[]}).rows.length,0);
console.log('Measured DPS: values preserved, empty snapshot, malformed/bounds rejected PASS');
