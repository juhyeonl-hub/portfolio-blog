import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {moduleUrl,plannerUrl} from './modules.mjs';
const points=await import(moduleUrl(readFileSync('lib/character-points.ts','utf8').replace("'./planner'",JSON.stringify(plannerUrl))));
const macro=await import(moduleUrl(readFileSync('lib/macro-evidence.ts','utf8')));
const catalog=JSON.parse(readFileSync('lib/data/catalogs/templar.json','utf8'));
const fixture=JSON.parse(readFileSync('tests/fixtures/templar-points-lv39.json','utf8'));
const character=fixture.character;
assert.deepEqual(points.characterPointReport(catalog,null).reasons,['character']);
assert.ok(points.characterPointReport(catalog,character,null).reasons.includes('gear'));
const missing=structuredClone(character);missing.skills=[];
assert.ok(points.characterPointReport(catalog,missing,{}).reasons.includes('skills'));
const bad=structuredClone(character);bad.skills[0].skillLevel=1000;
assert.ok(points.characterPointReport(catalog,bad,{}).reasons.includes('bonus'));
assert.equal(points.characterPointReport(catalog,bad,{}).spent.sp,null);
const board=structuredClone(character);board.failedBoards=['unavailable'];
assert.ok(points.characterPointReport(catalog,board,{}).reasons.includes('boards'));
assert.equal(points.characterPointReport(catalog,board,{}).spent.crystal,null);
assert.deepEqual(points.characterPointReport(catalog,character,{}).spent,points.characterPoints(catalog,character,{}));
const known=new Set(catalog.skills.map(s=>s.id));
assert.equal(macro.templarBasicAvailable('templar','pve',known),true);
for(const mode of ['pvp','leveling'])assert.equal(macro.templarBasicAvailable('templar',mode,known),false);
assert.equal(macro.templarBasicAvailable('ranger','pve',known),false);
known.delete('12100000');assert.equal(macro.templarBasicAvailable('templar','pve',known),false);
const ids=macro.TEMPLAR_BASIC.columns.flatMap(c=>c.skills);
for(const manual of ['12010000','12120000','12110000','12090000','12430000','12450000'])assert.ok(!ids.includes(manual));
assert.deepEqual(ids,['12100000','12350000','12240000','12340000','12040000']);
assert.match(macro.TEMPLAR_BASIC.source,/^https:\/\/aion2\.gaming\.tools\//);
console.log('Point diagnosis honesty and evidence-scoped macro regression PASS');
