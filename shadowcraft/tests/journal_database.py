"""Official quest/dungeon read-only browsing acceptance."""
import os
from playwright.sync_api import sync_playwright, expect
from _ui import click_tab
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1000})
    errors=[];requests=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:requests.append(r.url) if '/journal-index.json' in r.url else None)
    page.goto(os.environ.get('SHADOWCRAFT_TEST_URL','http://127.0.0.1:5173/lab/shadowcraft/'))
    click_tab(page,'글로벌 데이터')
    panel=page.get_by_role('region',name='공식 퀘스트·던전·펫 목록',exact=True)
    assert not requests
    before=page.evaluate('JSON.stringify(localStorage)')
    page.route('**/journal-index.json',lambda r:r.fulfill(json={'invalid':True}))
    panel.get_by_role('button',name='퀘스트·던전·펫 열기',exact=True).click()
    expect(panel.get_by_role('alert')).to_be_visible()
    page.unroute('**/journal-index.json')
    panel.get_by_role('button',name='퀘스트·던전·펫 다시 불러오기',exact=True).click()
    expect(panel).to_contain_text('퀘스트 1,429개 · 던전 733개')
    panel.get_by_role('button',name='목록 다음',exact=True).click()
    expect(panel.locator('.database-pages')).to_contain_text('2 / 48')
    panel.get_by_label('퀘스트·던전·펫 분류',exact=True).select_option('Hero')
    expect(panel).to_contain_text('퀘스트·던전·펫 검색 결과 239개')
    panel.get_by_label('퀘스트·던전·펫 검색',exact=True).fill('1100010')
    panel.locator('.database-list button').click()
    detail=panel.get_by_label('퀘스트·던전·펫 상세',exact=True)
    expect(detail).to_contain_text('Poeta')
    expect(detail).to_contain_text('연결된 보상 레코드가 없습니다.')
    detail.get_by_role('button').click()
    expect(detail).to_contain_text('1101010')
    expect(detail).to_contain_text('시작 NPC:')
    expect(detail).to_contain_text('완료 NPC:')
    expect(detail.get_by_role('region',name='퀘스트 보상')).to_contain_text('경험치 1,133')
    expect(detail).to_contain_text('1,400')
    panel.get_by_label('퀘스트·던전·펫 검색',exact=True).fill('1102011')
    panel.locator('.database-list button').click()
    expect(detail).to_contain_text('선택 보상 후보')
    expect(detail).to_contain_text('모든 아이템을 함께 받는다는 뜻은 아닙니다.')
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.set_viewport_size({'width':1440,'height':1000})
    panel.get_by_label('퀘스트·던전·펫 검색',exact=True).fill('1102010')
    panel.locator('.database-list button').click()
    expect(detail.get_by_label('직업별 퀘스트 보상')).to_contain_text('해당 직업만')
    detail.get_by_text('검성',exact=True).click()
    expect(detail.get_by_label('직업별 퀘스트 보상').locator('details[open]')).to_contain_text('× 1')
    expect(detail.get_by_label('퀘스트 레벨 조건')).to_contain_text('시작 레벨')
    panel.get_by_role('button',name='던전',exact=True).click()
    expect(panel).to_contain_text('퀘스트·던전·펫 검색 결과 733개')
    panel.get_by_label('퀘스트·던전·펫 분류',exact=True).select_option('Party')
    expect(panel).to_contain_text('퀘스트·던전·펫 검색 결과 55개')
    panel.locator('.database-list button').first.click()
    expect(detail).to_contain_text('연결 맵:')
    expect(detail.get_by_label('던전 권장 정보')).to_contain_text('입장 제한을 뜻하지 않습니다.')
    panel.get_by_label('퀘스트·던전·펫 검색',exact=True).fill('no-such-entry-xyz')
    expect(panel.get_by_role('status')).to_contain_text('검색 결과가 없습니다.')
    panel.get_by_role('button',name='펫',exact=True).click()
    expect(panel).to_contain_text('검색 결과 209개')
    panel.get_by_label('퀘스트·던전·펫 검색',exact=True).fill('Black Dragon')
    panel.locator('.database-list button').click()
    expect(detail).to_contain_text('ID 1001 · Special')
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    assert page.evaluate('JSON.stringify(localStorage)')==before
    assert not errors,errors
    browser.close()
print('Journal: lazy load, invalid/retry, filter/paging, quest chain, dungeon maps, mobile, unchanged storage PASS')
