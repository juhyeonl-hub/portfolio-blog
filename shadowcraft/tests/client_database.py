"""Browser acceptance against the bundled Global client index."""
import json
import os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

url = os.environ.get('SHADOWCRAFT_TEST_URL', 'http://127.0.0.1:5173/lab/shadowcraft/')
data = json.loads((Path(__file__).parents[2]/'frontend/public/shadowcraft/data/client-index.json').read_text())
recipe = next(r for r in data['recipes'] if r['ingredients'])
items = {i['id']: i for i in data['items']}
with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    page = browser.new_page(viewport={'width':1440, 'height':1000})
    errors, posts = [], []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('request', lambda r: posts.append(r.url) if r.method == 'POST' else None)
    page.route('**/api/public/shadowcraft/catalog?*', lambda r: r.fulfill(status=503,json={}))
    page.goto(url)
    page.get_by_role('button',name='공식 글로벌 설명 보기',exact=True).click()
    panel = page.get_by_role('region',name='글로벌 클라이언트 데이터베이스',exact=True)
    expect(panel.get_by_role('button',name='아이템 (9308)',exact=True)).to_be_visible()
    expect(panel.locator('.database-detail')).to_contain_text('공식 글로벌 스킬 설명')
    before = page.evaluate("Object.fromEntries(Object.entries(localStorage).filter(([k])=>k.startsWith('shadowcraft-plan-')))")
    panel.get_by_role('button',name='플레이어 스킬 (280)',exact=True).click()
    panel.get_by_label('데이터 검색',exact=True).fill('Quick Slice')
    expect(panel.locator('.database-list button')).to_have_count(1)
    panel.locator('.database-list button').click()
    expect(panel.locator('.skill-learning-list li')).to_have_count(10)
    description = panel.get_by_label('공식 글로벌 스킬 설명', exact=True)
    expect(description).to_contain_text('restores 100 MP')
    expect(description).to_contain_text('[unresolved value]')
    assert '{se_' not in description.inner_text()
    expect(panel.locator('.skill-learning-list li').nth(4)).to_contain_text('캐릭터 Lv.10')
    expect(panel.locator('.skill-learning-list li').nth(4)).to_contain_text('SP 2')
    panel.get_by_label('데이터 검색',exact=True).fill('13020000')
    panel.locator('.database-list button').click()
    expect(description).to_contain_text('reduces Move Speed by 40% for 5s')
    expect(description).to_contain_text('클라이언트 기본값 기준')
    gated = next(s for s in data['skills'] if any(r['ascensionRequirement'] != 'None' for r in s['learning']))
    panel.get_by_label('데이터 검색',exact=True).fill(gated['id'])
    panel.locator('.database-list button').click()
    expect(panel.locator('.skill-learning-list')).to_contain_text('AscensionGrade_3')
    panel.get_by_role('button',name='제작법 (1098)',exact=True).click()
    panel.get_by_label('데이터 검색',exact=True).fill('211043001')
    panel.locator('.database-list button').click()
    probability = panel.get_by_role('region',name='제작 기본 예상 확률',exact=True)
    expect(probability.get_by_role('status')).to_have_text('기본 예상 성공 확률: 약 67.51%')
    for gap, expected in [('10', '79.03'), ('44', '94.01'), ('65', '94.64')]:
        probability.get_by_label('숙련도 레벨 차이',exact=True).fill(gap)
        expect(probability.get_by_role('status')).to_contain_text(expected+'%')
    for gap in ['', '-1', '1.5', '999', 'abc']:
        probability.get_by_label('숙련도 레벨 차이',exact=True).fill(gap)
        expect(probability.get_by_role('alert')).to_be_visible()
        expect(probability.get_by_role('status')).to_have_count(0)
    probability.get_by_text('숙련도 차이별 확률표',exact=True).click()
    expect(probability.locator('tbody tr')).to_have_count(66)
    missing = next(r for r in data['recipes'] if r.get('baseRateCurve') is None)
    panel.get_by_label('데이터 검색',exact=True).fill(missing['id'])
    panel.locator('.database-list button').click()
    expect(panel.locator('.database-detail')).to_contain_text('기본 예상 확률표가 없습니다.')
    panel.get_by_label('데이터 검색',exact=True).fill(recipe['id'])
    expect(panel.locator('.database-list button')).to_have_count(1)
    panel.locator('.database-list button').click()
    expect(panel.get_by_label('숙련도 레벨 차이',exact=True)).to_have_value('0')
    combo = next(r for r in data['recipes'] if r['id'] == recipe['comboRecipeId'])
    panel.get_by_label('연결된 제작 결과',exact=True).get_by_role('button').click()
    expect(panel.locator('.database-detail')).to_contain_text('레시피 ' + combo['id'])
    panel.get_by_label('이 결과를 연결하는 제작법',exact=True).get_by_role('button',name=items[recipe['itemId']]['name']+' · '+recipe['id'],exact=True).click()
    expect(panel.locator('.database-detail')).to_contain_text('레시피 ' + recipe['id'])
    panel.get_by_label('제작 시도 횟수',exact=True).fill('3')
    succession = next(r for r in data['recipes'] if r.get('successionCandidateItemIds'))
    panel.get_by_label('데이터 검색',exact=True).fill(succession['id'])
    panel.locator('.database-list button').click()
    expect(panel.locator('.database-detail')).to_contain_text('제작 유형: 계승 제작')
    candidates = panel.get_by_label('계승 대상 후보',exact=True)
    expect(candidates.get_by_role('button')).to_have_count(len(succession['successionCandidateItemIds']))
    candidate = succession['successionCandidateItemIds'][0]
    candidates.get_by_role('button',name=items[candidate]['name']+' · ID '+candidate,exact=True).click()
    expect(panel.locator('.database-detail')).to_contain_text('ID '+candidate)
    panel.get_by_role('button',name='제작법 (1098)',exact=True).click()
    panel.get_by_label('데이터 검색',exact=True).fill(recipe['id'])
    panel.locator('.database-list button').click()
    panel.get_by_label('제작 시도 횟수',exact=True).fill('3')
    ingredient = recipe['ingredients'][0]
    expect(panel.locator('.database-detail')).to_contain_text(items[ingredient['itemId']]['name']+' × '+format(ingredient['quantity']*3,','))
    panel.get_by_label('제작 시도 횟수',exact=True).fill('-1')
    expect(panel.get_by_role('alert')).to_be_visible()
    expect(panel.locator('.database-detail li')).to_have_count(0)
    panel.get_by_label('제작 시도 횟수',exact=True).fill('3')
    page.get_by_role('tab',name='스킬 & 특화',exact=True).click()
    page.get_by_role('tab',name='글로벌 데이터',exact=True).click()
    expect(panel.get_by_label('제작 시도 횟수',exact=True)).to_have_value('3')
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    page.screenshot(path='/tmp/a2bc-client-database-mobile.png',full_page=True)
    assert before == page.evaluate("Object.fromEntries(Object.entries(localStorage).filter(([k])=>k.startsWith('shadowcraft-plan-')))")
    assert not errors, errors
    assert not posts, posts
    # Malformed server response must show retry rather than crash the application.
    page.route('**/shadowcraft/data/client-index.json',lambda r:r.fulfill(json={'schema':'broken'}))
    page.reload()
    page.get_by_role('tab',name='글로벌 데이터',exact=True).click()
    expect(panel.get_by_role('alert')).to_be_visible()
    page.unroute('**/shadowcraft/data/client-index.json')
    panel.get_by_role('button',name='다시 불러오기',exact=True).click()
    expect(panel.get_by_role('button',name='아이템 (9308)',exact=True)).to_be_visible()
    assert not errors, errors
    browser.close()
print('Client database: official references, search, material attempts, invalid input, tab retention, storage, mobile and retry PASS')
